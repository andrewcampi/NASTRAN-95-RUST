      PROGRAM INSDRV
C
C     FIXED-INPUT PARITY DRIVER FOR INSERT (mis/insert.f)
C     PRINTS ONLY DETERMINISTIC FIXED-FORMAT TEXT.
C
C     INSERT SCATTERS ONE IS2D8 MATRIX PARTITION (TEMP/DTEMP) INTO THE
C     OPEN CORE ARRAYS Z/DZ AT THE BASE OFFSETS IZ1 (THE PARTITION) AND
C     IZ2 (ITS TRANSPOSE).  FOUR CALLS COVER THE FOUR BRANCHES:
C
C       CASE 1: IPR=1, NDOF=3   3X3 SINGLE PRECISION
C       CASE 2: IPR=1, NDOF=1   1X1 SINGLE PRECISION
C       CASE 3: IPR=2, NDOF=3   3X3 DOUBLE PRECISION
C       CASE 4: IPR=2, NDOF=1   1X1 DOUBLE PRECISION
C
C     Z/DZ ARE ZEROED BEFORE EVERY CALL AND ONLY THE NON-ZERO SLOTS ARE
C     PRINTED, SO THE OUTPUT PINS BOTH THE SET OF SLOTS INSERT TOUCHES
C     AND THE VALUE IT WRITES INTO EACH ONE.  TEMP/DTEMP HOLD DISTINCT
C     NON-ZERO VALUES SO EVERY SCATTER PAIR IS IDENTIFIABLE.
C
      REAL Z(200), TEMP(9)
      DOUBLE PRECISION DZ(200), DTEMP(9)
      INTEGER NCOL, NROW, NDOF, NGRID, JCORE, IPR
      INTEGER I, K
C
      DO 200 K = 1, 4
C
C       CLEAR THE OPEN CORE WINDOW AND THE PARTITION
C
        DO 10 I = 1, 200
          Z(I) = 0.0
          DZ(I) = 0.0
   10   CONTINUE
        DO 20 I = 1, 9
          TEMP(I) = REAL(I)
          DTEMP(I) = DBLE(I) + 0.25D0
   20   CONTINUE
C
C       PER-CASE ARGUMENTS.  NCOL/NROW ARE SWAPPED BETWEEN THE SINGLE
C       AND DOUBLE CASES SO IZ1 AND IZ2 ARE NOT ALWAYS IN THE SAME ORDER.
C
        IF (K .EQ. 1) THEN
          IPR = 1
          NDOF = 3
          NGRID = 2
          NCOL = 2
          NROW = 3
          JCORE = 1
        ELSE IF (K .EQ. 2) THEN
          IPR = 1
          NDOF = 1
          NGRID = 3
          NCOL = 2
          NROW = 3
          JCORE = 2
        ELSE IF (K .EQ. 3) THEN
          IPR = 2
          NDOF = 3
          NGRID = 2
          NCOL = 3
          NROW = 2
          JCORE = 1
        ELSE
          IPR = 2
          NDOF = 1
          NGRID = 3
          NCOL = 3
          NROW = 2
          JCORE = 2
        END IF
C
        CALL INSERT(NCOL,NROW,NDOF,NGRID,JCORE,Z,DZ,TEMP,DTEMP,IPR)
C
        WRITE(6,900) K, IPR, NDOF, NGRID, NCOL, NROW, JCORE
        DO 30 I = 1, 200
          IF (Z(I) .NE. 0.0) WRITE(6,910) K, I, Z(I)
   30   CONTINUE
        DO 40 I = 1, 200
          IF (DZ(I) .NE. 0.0D0) WRITE(6,920) K, I, DZ(I)
   40   CONTINUE
  200 CONTINUE
      STOP
C
  900 FORMAT('CASE ',I1,' IPR=',I1,' NDOF=',I1,' NGRID=',I1,' NCOL=',I1,
     &       ' NROW=',I1,' JCORE=',I1)
  910 FORMAT('CASE ',I1,' Z ',I3,1X,F8.1)
  920 FORMAT('CASE ',I1,' DZ ',I3,1X,F10.2)
      END
