      PROGRAM DBMMOVDRV
C
C     FIXED-INPUT PARITY DRIVER FOR DBMMOV (mis/dbmmov.f)
C     PRINTS ONLY DETERMINISTIC FIXED-FORMAT TEXT.
C
C     DBMMOV COPIES NO WORDS WITHIN THE IN-MEMORY DATABASE:
C
C       DO 10 I = 1, NO
C       MEM( INDEX2+I-1 ) = MEM( INDEX1+I-1 )
C    10 CONTINUE
C
C     THE COPY IS A FORWARD LOOP, SO OVERLAPPING RANGES BEHAVE LIKE THE
C     FORTRAN (FORWARD COPY, NOT MEMMOVE).  THREE CASES PIN THAT:
C
C       CASE 1: INDEX1=1, INDEX2=11, NO=5   NON-OVERLAPPING COPY
C       CASE 2: INDEX1=1, INDEX2=3,  NO=5   OVERLAPPING FORWARD COPY
C       CASE 3: INDEX1=1, INDEX2=11, NO=0   NO-OP (DO 10 I = 1, 0)
C
C     MEM(1..20) IS SEEDED ONCE WITH A FIXED PATTERN AND PRINTED AFTER
C     EVERY CALL, SO THE OUTPUT PINS BOTH THE WORDS DBMMOV WRITES AND
C     THE FORWARD-COPY ORDER OF THE OVERLAPPING CASE.
C
      INTEGER MEM(20)
      COMMON / ZZZZZZ / MEM
      INTEGER I, K, INDEX1, INDEX2, NO
C
      DO 5 I = 1, 20
        MEM(I) = 1000 + I
    5 CONTINUE
C
      DO 200 K = 1, 3
C
C       PER-CASE ARGUMENTS
C
        IF (K .EQ. 1) THEN
          INDEX1 = 1
          INDEX2 = 11
          NO = 5
        ELSE IF (K .EQ. 2) THEN
          INDEX1 = 1
          INDEX2 = 3
          NO = 5
        ELSE
          INDEX1 = 1
          INDEX2 = 11
          NO = 0
        END IF
C
        CALL DBMMOV(INDEX1,INDEX2,NO)
C
        WRITE(6,900) K, INDEX1, INDEX2, NO
        DO 30 I = 1, 20
          WRITE(6,910) I, MEM(I)
   30   CONTINUE
  200 CONTINUE
      STOP
C
  900 FORMAT('CASE ',I1,' INDEX1=',I3,' INDEX2=',I3,' NO=',I3)
  910 FORMAT('MEM ',I3,I12)
      END
