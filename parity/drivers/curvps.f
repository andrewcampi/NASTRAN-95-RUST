      PROGRAM CVDRV
C
C     FIXED-INPUT UNIT DRIVER FOR CURVPS
C     PRINTS ONLY DETERMINISTIC FIXED-FORMAT TEXT
C
      REAL SIGS(3), PRIN(4)
      INTEGER I
C
C     CASE 1: GENERAL BIAXIAL STATE WITH SHEAR
C
      SIGS(1) = 100.0
      SIGS(2) = 50.0
      SIGS(3) = 25.0
      CALL CURVPS(SIGS,PRIN)
      WRITE(6,910) 1
      DO 10 I = 1,4
         WRITE(6,900) I,PRIN(I)
   10 CONTINUE
C
C     CASE 2: NEGATIVE COMPONENTS AND NEGATIVE SHEAR
C
      SIGS(1) = -30.0
      SIGS(2) = 20.0
      SIGS(3) = -12.5
      CALL CURVPS(SIGS,PRIN)
      WRITE(6,910) 2
      DO 20 I = 1,4
         WRITE(6,900) I,PRIN(I)
   20 CONTINUE
C
C     CASE 3: DEGENERATE - SIGS(1)=SIGS(2) AND SIGS(3)=0 TAKES
C             THE PRIN(1) = 0.0 BRANCH
C
      SIGS(1) = 1.0
      SIGS(2) = 1.0
      SIGS(3) = 0.0
      CALL CURVPS(SIGS,PRIN)
      WRITE(6,910) 3
      DO 30 I = 1,4
         WRITE(6,900) I,PRIN(I)
   30 CONTINUE
C
  900 FORMAT('PRIN(',I1,') = ',ES24.16E3)
  910 FORMAT('CASE ',I1)
      STOP
      END
